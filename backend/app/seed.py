"""Seed / demo mode (§37).

    python -m app.seed --demo            full demo: projects, floors, plans, captures, reports
    python -m app.seed --users-only      just the four role accounts
    python -m app.seed --demo --quick    fewer, smaller frames (fast smoke test)
    python -m app.seed --reset           drop and recreate everything first

All imagery is generated by :mod:`app.processing.synthetic` and
:mod:`app.processing.floorplan_render`. Nothing is downloaded, and no third-party dataset or
proprietary imagery is used (§37).

Progress over time is simulated the honest way — the *building changes*. Each successive capture
date renders the room with one more structural column cast and slightly different lighting, so
the compare view shows a genuine physical difference between dates rather than the same photo
twice.
"""

