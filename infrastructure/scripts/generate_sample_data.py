#!/usr/bin/env python
"""Write the demo imagery to ``sample-data/`` as ordinary files (§37).

    python infrastructure/scripts/generate_sample_data.py
    python infrastructure/scripts/generate_sample_data.py --width 4096 --frames 8
    python infrastructure/scripts/generate_sample_data.py --video

The seeder (``python -m app.seed --demo``) already generates this imagery straight into storage,
so this script is not needed to run the platform. It exists so the files can be inspected, opened
in another viewer, or uploaded by hand through the UI to exercise the upload path end to end.

Everything written here is produced by :mod:`app.processing.synthetic` and
:mod:`app.processing.floorplan_render`. Nothing is downloaded, and no third-party or proprietary
imagery is involved.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "backend"))

from app.processing.floorplan_render import (  # noqa: E402
    PX_PER_METER,
    render_floor_plan,
    world_to_plan_px,
)
from app.processing.media import encode_jpeg  # noqa: E402
from app.processing.synthetic import (  # noqa: E402
    DEFAULT_STEP_M,
    Room,
    default_walk,
    render_panorama,
)

OUTPUT = REPO_ROOT / "sample-data"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--width",
        type=int,
        default=2048,
        help="panorama width in pixels (height is half). 4096 scores 'good' on quality.",
    )
    parser.add_argument(
        "--frames",
        type=int,
        default=6,
        help="how many positions along the walk to render (0 = the whole walk)",
    )
    parser.add_argument(
        "--step-m",
        type=float,
        default=DEFAULT_STEP_M,
        help="metres between positions. Above ~4 m, mapping will correctly refuse.",
    )
    parser.add_argument(
        "--video",
        action="store_true",
        help="also write a 360 MP4 walkthrough (needs an OpenCV build that can encode MP4)",
    )
    args = parser.parse_args(argv)

    room = Room()
    height = args.width // 2
    positions = default_walk(room, step_m=args.step_m)
    if args.frames > 0:
        positions = positions[: args.frames]

    panoramas = OUTPUT / "panoramas"
    floorplans = OUTPUT / "floorplans"
    panoramas.mkdir(parents=True, exist_ok=True)
    floorplans.mkdir(parents=True, exist_ok=True)

    # ---- floor plan -----------------------------------------------------
    png, plan_w, plan_h, scale = render_floor_plan(
        room, title="Ground — General Arrangement", project_code="SAMPLE"
    )
    plan_path = floorplans / "ground-floor-plan.png"
    plan_path.write_bytes(png)
    print(f"wrote {plan_path.relative_to(REPO_ROOT)}  ({plan_w}x{plan_h}px, {scale:.0f} px/m)")

    # ---- panoramas ------------------------------------------------------
    manifest: list[dict[str, object]] = []
    for index, position in enumerate(positions):
        image = render_panorama(room, position, width=args.width, height=height)
        name = f"PANO_{index:03d}.jpg"
        (panoramas / name).write_bytes(encode_jpeg(image, quality=90))

        plan_x, plan_y = world_to_plan_px(room, position[0], position[2], px_per_meter=PX_PER_METER)
        manifest.append(
            {
                "file": f"panoramas/{name}",
                "sequence": index,
                # The camera position that produced this image. Useful for checking the vision
                # engine's estimate against the truth, which is the point of generating rather
                # than downloading.
                "camera_world_xz_m": [round(position[0], 3), round(position[2], 3)],
                "floor_plan_px": [round(plan_x, 1), round(plan_y, 1)],
                "width_px": args.width,
                "height_px": height,
            }
        )
        print(f"wrote sample-data/panoramas/{name}  ({args.width}x{height})")

    # ---- optional video -------------------------------------------------
    if args.video:
        written = _write_video(room, args.width, height)
        if written:
            print(f"wrote {written.relative_to(REPO_ROOT)}")
        else:
            print("skipped video: this OpenCV build cannot encode MP4", file=sys.stderr)

    # ---- manifest -------------------------------------------------------
    manifest_path = OUTPUT / "manifest.json"
    manifest_path.write_text(
        json.dumps(
            {
                "generated_by": "infrastructure/scripts/generate_sample_data.py",
                "source": "backend/app/processing/synthetic.py",
                "licence": "Generated by this repository. Public domain; no third-party imagery.",
                "room": {
                    "width_m": room.width_m,
                    "depth_m": room.depth_m,
                    "columns": [[c.x, c.z] for c in room.columns],
                },
                "floor_plan": {
                    "file": "floorplans/ground-floor-plan.png",
                    "width_px": plan_w,
                    "height_px": plan_h,
                    "px_per_meter": scale,
                },
                "step_m": args.step_m,
                "frames": manifest,
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"wrote {manifest_path.relative_to(REPO_ROOT)}")
    return 0


def _write_video(room: Room, width: int, height: int) -> Path | None:
    import cv2  # noqa: PLC0415

    path = OUTPUT / "panoramas" / "walkthrough.mp4"
    fps, seconds = 10, 8
    writer = cv2.VideoWriter(str(path), cv2.VideoWriter_fourcc(*"mp4v"), fps, (width, height))
    if not writer.isOpened():
        writer.release()
        return None

    total = fps * seconds
    for index in range(total):
        # A straight traverse of the room, so extracted frames have genuine parallax.
        x = -7.0 + 14.0 * index / total
        writer.write(render_panorama(room, (x, 0.0, 0.0), width=width, height=height))
    writer.release()
    return path


if __name__ == "__main__":
    sys.exit(main())
