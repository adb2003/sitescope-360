DEMO_PASSWORD = "SiteScope360!demo"

ACCOUNTS = [
    ("admin@demo.example.com", "Aditya Bhandari", Role.ADMIN),
    ("manager@demo.example.com", "Priya Raman", Role.PROJECT_MANAGER),
    ("engineer@demo.example.com", "Sam Okafor", Role.SITE_ENGINEER),
    ("viewer@demo.example.com", "Jules Tan", Role.VIEWER),
]

ZONE_LAYOUT = [
    ("North", 2400.0, 6),
    ("South", 2400.0, 6),
    ("East", 1800.0, 4),
    ("West", 1800.0, 4),
]

#: Days before today for each demo capture, newest last — the §37 "Day 1/3/7/10" pattern.
CAPTURE_DAYS_AGO = [10, 7, 3, 0]


def seed_users(db) -> dict[str, User]:
    from app.auth.security import hash_password

    created: dict[str, User] = {}
    password_hash = hash_password(DEMO_PASSWORD)
    for email, name, role in ACCOUNTS:
        user = db.scalar(select(User).where(User.email == email))
        if user is None:
            user = User(email=email, full_name=name, password_hash=password_hash, role=role)
            db.add(user)
            logger.info("Created %s (%s)", email, role)
        created[str(role)] = user
    db.commit()
    return created


def seed_demo(db, *, quick: bool = False) -> dict[str, object]:
    users = seed_users(db)
    admin = users[str(Role.ADMIN)]
    manager = users[str(Role.PROJECT_MANAGER)]
    engineer = users[str(Role.SITE_ENGINEER)]

    storage = get_storage()
    room = Room()

    width, height = (1024, 512) if quick else (2048, 1024)
    step_m = 3.0 if quick else 1.5
    capture_days = CAPTURE_DAYS_AGO[:2] if quick else CAPTURE_DAYS_AGO

    # ---- primary demo project ------------------------------------------
    project = db.scalar(select(Project).where(Project.code == "DEMO-001"))
    if project is None:
        project = Project(
            name="Demo Construction Project",
            code="DEMO-001",
            client="Northgate Developments",
            location="Unit 4, Riverside Industrial Estate",
            description=(
                "Demo project seeded by SiteScope 360. All imagery is procedurally generated; "
                "no external or proprietary data is used."
            ),
            status=ProjectStatus.ACTIVE,
            start_date=(datetime.now(UTC) - timedelta(days=120)).date(),
            expected_completion_date=(datetime.now(UTC) + timedelta(days=240)).date(),
            project_manager_id=manager.id,
            created_by_id=admin.id,
            expected_captures_per_week=2,
        )
        db.add(project)
        db.flush()
        _staff(db, project, users, added_by_id=admin.id)
        db.commit()
        logger.info("Created project %s", project.code)

    building = _get_or_create_building(db, project, "Building A")
    floors = [
        _get_or_create_floor(db, building, "Ground", 0, 8000.0, 0.0),
        _get_or_create_floor(db, building, "Level 01", 1, 8400.0, 3.6),
        _get_or_create_floor(db, building, "Level 02", 2, 8400.0, 7.2),
    ]
    for floor in floors:
        for name, area, expected_points in ZONE_LAYOUT:
            _get_or_create_zone(db, floor, name, area, expected_points)
    db.commit()

    # ---- floor plans ----------------------------------------------------
    for floor in floors:
        if db.scalar(select(FloorPlan.id).where(FloorPlan.floor_id == floor.id)):
            continue
        png, plan_w, plan_h, scale = render_floor_plan(
            room,
            title=f"{floor.name} — General Arrangement",
            project_code=project.code,
        )
        plan_id = new_id()
        key = floorplan_key(project.id, floor.id, f"{plan_id}.png")
        storage.put_bytes(key, png, "image/png")
        db.add(
            FloorPlan(
                id=plan_id,
                floor_id=floor.id,
                name=f"{floor.name} GA drawing",
                storage_key=key,
                content_type="image/png",
                width_px=plan_w,
                height_px=plan_h,
                file_size_bytes=len(png),
                px_per_meter=scale,
                calibration={
                    "provenance": "measured",
                    "note": (
                        "Exact: this drawing was rendered from the same room model as the "
                        "demo panoramas, so the scale is known rather than estimated."
                    ),
                },
                is_active=True,
                uploaded_by_id=admin.id,
            )
        )
        logger.info("Uploaded floor plan for %s (%dx%d px)", floor.name, plan_w, plan_h)
    db.commit()

    # ---- camera device --------------------------------------------------
    if not db.scalar(select(CameraDevice.id).where(CameraDevice.label == "Site 360 unit 1")):
        db.add(
            CameraDevice(
                label="Site 360 unit 1",
                make="Generic",
                model="360 Equirectangular",
                provider_key="local_upload",
                native_width_px=width,
                native_height_px=height,
                owner_id=admin.id,
                notes="Demo device. Files are uploaded manually — no camera SDK involved.",
            )
        )
        db.commit()

    # ---- capture sessions ----------------------------------------------
    ground = floors[0]
    plan = db.scalar(
        select(FloorPlan).where(FloorPlan.floor_id == ground.id, FloorPlan.is_active.is_(True))
    )
    zones = {zone.name: zone for zone in db.scalars(select(Zone).where(Zone.floor_id == ground.id))}
    positions = default_walk(room, step_m=step_m)
    # The newest walkthrough closes its loop. The others are open paths, so the demo carries both
    # cases: three sessions where dead reckoning is all the imagery supports, and one where a
    # genuine revisit lets loop closure bound the drift. Without a closing walk the SLAM feature
    # would be invisible in the demo data, which is the same as not shipping it.
    loop_positions = loop_walk(room, step_m=step_m)

    existing_sessions = int(
        db.scalar(select(CaptureSession.id).where(CaptureSession.floor_id == ground.id).limit(1))
        is not None
    )
    session_ids: list[str] = []

    if not existing_sessions:
        for index, days_ago in enumerate(capture_days):
            started = datetime.now(UTC).replace(
                hour=9, minute=15, second=0, microsecond=0
            ) - timedelta(days=days_ago)

            # Construction progress: one more column cast at each visit, and the lighting
            # differs because the openings change. This is what the compare view will show.
            columns = room.columns[: min(len(room.columns), 2 + index)]
            scene = Room(columns=tuple(columns))
            brightness = 0.88 + 0.05 * index
            is_newest = days_ago == min(capture_days)
            walk = loop_positions if is_newest else positions

            session_id = _create_capture_session(
                db,
                project=project,
                building=building,
                floor=ground,
                zone=zones.get("North"),
                started=started,
                operator=engineer,
                name=(
                    f"{started:%d %B %Y} — Morning walkthrough"
                    + (" (full circuit)" if is_newest else "")
                ),
            )
            session_ids.append(session_id)

            logger.info(
                "Rendering %d panoramas for %s (%d columns, %s)",
                len(walk),
                session_id,
                len(columns),
                "closed circuit" if is_newest else "open path",
            )
            for order, position in enumerate(walk):
                image = render_panorama(
                    scene,
                    position,
                    width=width,
                    height=height,
                    brightness=brightness,
                )
                data = encode_jpeg(image, quality=88)
                file_id = new_id()
                key = session_key(project.id, ground.id, session_id, "source", f"{file_id}.jpg")
                storage.put_bytes(key, data, "image/jpeg")
                db.add(
                    CaptureFile(
                        id=file_id,
                        session_id=session_id,
                        original_filename=f"PANO_{order:03d}.jpg",
                        storage_key=key,
                        content_type="image/jpeg",
                        file_size_bytes=len(data),
                        captured_at=started + timedelta(seconds=order * 12),
                    )
                )
            db.commit()

            from app.workers.handlers import run_pipeline_inline

            logger.info("Processing %s", session_id)
            run_pipeline_inline(session_id)

            _place_frames(db, session_id, room, plan, positions, zones, admin.id)

        _seed_annotations(db, session_ids[-1], project, ground, engineer, manager)

    # ---- schedules ------------------------------------------------------
    if not db.scalar(select(CaptureSchedule.id).where(CaptureSchedule.project_id == project.id)):
        db.add(
            CaptureSchedule(
                project_id=project.id,
                floor_id=None,
                expected_per_week=2,
                grace_days=1,
                notes="Two walkthroughs per week while fit-out is in progress.",
            )
        )
        db.commit()

    # ---- a second, overdue project so the portfolio view has contrast ----
    _seed_overdue_project(db, admin, manager, users)

    return {
        "project_id": project.id,
        "floor_id": ground.id,
        "session_ids": session_ids,
        "accounts": [email for email, _, _ in ACCOUNTS],
        "password": DEMO_PASSWORD,
    }


# ---- helpers -----------------------------------------------------------------
def _get_or_create_building(db, project: Project, name: str) -> Building:
    building = db.scalar(
        select(Building).where(Building.project_id == project.id, Building.name == name)
    )
    if building is None:
        building = Building(project_id=project.id, name=name)
        db.add(building)
        db.commit()
    return building


def _get_or_create_floor(
    db, building: Building, name: str, level: int, area: float, elevation: float
) -> Floor:
    floor = db.scalar(select(Floor).where(Floor.building_id == building.id, Floor.name == name))
    if floor is None:
        floor = Floor(
            building_id=building.id,
            name=name,
            level=level,
            area_sqft=area,
            elevation_m=elevation,
        )
        db.add(floor)
        db.commit()
    return floor


def _get_or_create_zone(db, floor: Floor, name: str, area: float, expected_points: int) -> Zone:
    zone = db.scalar(select(Zone).where(Zone.floor_id == floor.id, Zone.name == name))
    if zone is None:
        zone = Zone(
            floor_id=floor.id,
            name=name,
            area_sqft=area,
            expected_capture_points=expected_points,
            description=f"{name} wing",
        )
        db.add(zone)
        db.commit()
    return zone


def _create_capture_session(
    db,
    *,
    project: Project,
    building: Building,
    floor: Floor,
    zone: Zone | None,
    started: datetime,
    operator: User,
    name: str,
) -> str:
    session_id = new_capture_session_id(started)
    db.add(
        CaptureSession(
            id=session_id,
            project_id=project.id,
            building_id=building.id,
            floor_id=floor.id,
            zone_id=zone.id if zone else None,
            name=name,
            started_at=started,
            ended_at=started + timedelta(minutes=18),
            operator_id=operator.id,
            capture_source=CaptureSource.HUMAN_OPERATOR,
            camera_label="Generic 360 Equirectangular",
            notes="Seeded demo capture — procedurally generated imagery.",
        )
    )
    db.commit()
    return session_id


def _place_frames(
    db,
    session_id: str,
    room: Room,
    plan: FloorPlan | None,
    positions: list[tuple[float, float, float]],
    zones: dict[str, Zone],
    created_by_id: str,
) -> None:
    """Bind each frame to a floor-plan location at the position the camera actually occupied.

    Locations are created once per floor and reused by later sessions — which is exactly what
    makes date-over-date comparison work, since both visits share a ``location_id``.
    """
    from app.core.ids import location_code
    from app.models import CaptureLocation
    from app.processing.stages import build_capture_path

    session = db.get(CaptureSession, session_id)
    if session is None or plan is None:
        return

    frames = list(
        db.scalars(
            select(CaptureFrame)
            .where(CaptureFrame.session_id == session_id)
            .order_by(CaptureFrame.sequence_index)
        )
    )

    for index, frame in enumerate(frames):
        if index >= len(positions):
            break
        x_m, _, z_m = positions[index]
        plan_x, plan_y = world_to_plan_px(room, x_m, z_m, px_per_meter=PX_PER_METER)
        code = location_code(index + 1)

        location = db.scalar(
            select(CaptureLocation).where(
                CaptureLocation.floor_id == session.floor_id,
                CaptureLocation.code == code,
            )
        )
        if location is None:
            # Assign a zone by which half of the room the point sits in, so zone coverage in the
            # demo reflects where the operator actually walked.
            zone_name = "North" if z_m >= 0 else "South"
            location = CaptureLocation(
                floor_id=session.floor_id,
                zone_id=zones[zone_name].id if zone_name in zones else None,
                floor_plan_id=plan.id,
                code=code,
                label=f"{code} — {zone_name} wing",
                x=plan_x,
                y=plan_y,
                provenance=DataProvenance.MANUAL,
                created_by_id=created_by_id,
            )
            db.add(location)
            db.flush()

        frame.location_id = location.id
        frame.position_provenance = DataProvenance.MANUAL
        frame.position_confidence = 1.0

    db.flush()
    build_capture_path(db, session)
    db.commit()


def _seed_annotations(
    db, session_id: str, project: Project, floor: Floor, engineer: User, manager: User
) -> None:
    frames = list(
        db.scalars(
            select(CaptureFrame)
            .where(CaptureFrame.session_id == session_id)
            .order_by(CaptureFrame.sequence_index)
            .limit(6)
        )
    )
    if not frames:
        return

    samples = [
        (
            "Missing ceiling panel above grid C4",
            AnnotationPriority.MEDIUM,
            AnnotationStatus.OPEN,
            42.0,
            24.0,
        ),
        (
            "Column formwork not stripped",
            AnnotationPriority.LOW,
            AnnotationStatus.IN_PROGRESS,
            155.0,
            -3.0,
        ),
        (
            "Water ingress at south wall base",
            AnnotationPriority.HIGH,
            AnnotationStatus.OPEN,
            -96.0,
            -28.0,
        ),
        (
            "Temporary lighting obstructs egress route",
            AnnotationPriority.CRITICAL,
            AnnotationStatus.OPEN,
            12.0,
            11.0,
        ),
        (
            "Blockwork joint finish approved",
            AnnotationPriority.LOW,
            AnnotationStatus.RESOLVED,
            -140.0,
            6.0,
        ),
    ]
    for index, (title, priority, status, yaw, pitch) in enumerate(samples):
        frame = frames[index % len(frames)]
        db.add(
            Annotation(
                frame_id=frame.id,
                project_id=project.id,
                floor_id=floor.id,
                yaw_deg=yaw,
                pitch_deg=pitch,
                title=title,
                description=(
                    "Seeded demo annotation. Recorded manually by a site engineer — the platform "
                    "does not detect defects automatically (that is a Phase 3 capability)."
                ),
                priority=priority,
                status=status,
                created_by_id=engineer.id,
                assigned_to_id=manager.id if priority == AnnotationPriority.CRITICAL else None,
                resolved_at=(
                    datetime.now(UTC) - timedelta(days=1)
                    if status == AnnotationStatus.RESOLVED
                    else None
                ),
            )
        )
    db.commit()
    logger.info("Seeded %d annotations", len(samples))


def _seed_overdue_project(db, admin: User, manager: User, users: dict) -> None:
    """A project whose last capture is well past due, so the portfolio view has real contrast."""
    project = db.scalar(select(Project).where(Project.code == "DEMO-002"))
    if project is not None:
        return

    project = Project(
        name="Riverside Warehouse Fit-out",
        code="DEMO-002",
        client="Meridian Logistics",
        location="Bay 12, Riverside",
        status=ProjectStatus.ACTIVE,
        start_date=(datetime.now(UTC) - timedelta(days=60)).date(),
        project_manager_id=manager.id,
        created_by_id=admin.id,
        expected_captures_per_week=2,
    )
    db.add(project)
    db.flush()
    _staff(db, project, users, added_by_id=admin.id)
    db.commit()

    building = _get_or_create_building(db, project, "Warehouse")
    floor = _get_or_create_floor(db, building, "Ground", 0, 24000.0, 0.0)
    _get_or_create_zone(db, floor, "Racking bay", 12000.0, 8)
    _get_or_create_zone(db, floor, "Loading dock", 6000.0, 4)
    db.commit()
    logger.info(
        "Created %s with no captures — it will report as never captured / overdue", project.code
    )


def _staff(db: Session, project: Project, users: dict, *, added_by_id: str) -> None:
    """Put every demo account on a demo project (§27).

    Projects are only visible to their members now, and the demo exists to be opened by whichever
    role the reader signs in as — a seeded dataset that shows nothing to three of its four
    accounts would look like a broken deployment rather than a working permission model. The
    scoping itself is demonstrated by `tests/integration/test_project_scoping.py`, which is the
    right place for it: a demo should show the product, not its access-control edge cases.
    """
    for account in users.values():
        grant(db, project.id, account.id, added_by_id=added_by_id)


# ---- entrypoint --------------------------------------------------------------
def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Seed SiteScope 360 with demo data")
    parser.add_argument("--demo", action="store_true", help="seed the full demo dataset")
    parser.add_argument("--users-only", action="store_true", help="seed only the role accounts")
    parser.add_argument(
        "--quick", action="store_true", help="fewer and smaller frames (fast smoke test)"
    )
    parser.add_argument(
        "--reset",
        action="store_true",
        help="DROP every table and recreate before seeding",
    )
    args = parser.parse_args(argv)

    configure_logging(json_output=False)

    if not (args.demo or args.users_only):
        parser.print_help()
        return 1

    if args.reset:
        if settings.environment == "production":
            logger.error("--reset refuses to run with ENVIRONMENT=production")
            return 2
        logger.warning("Dropping every table in %s", settings.database_url)
        Base.metadata.drop_all(engine)
        Base.metadata.create_all(engine)

    db = SessionLocal()
    try:
        if args.users_only:
            seed_users(db)
            logger.info("Seeded %d accounts, password: %s", len(ACCOUNTS), DEMO_PASSWORD)
            return 0

        result = seed_demo(db, quick=args.quick)
        logger.info("Demo data ready")
        logger.info("  project_id : %s", result["project_id"])
        logger.info("  sessions   : %s", result["session_ids"])
        logger.info("  sign in as : %s", ACCOUNTS[0][0])
        logger.info("  password   : %s", DEMO_PASSWORD)
        return 0
    finally:
        db.close()


if __name__ == "__main__":
    sys.exit(main())
